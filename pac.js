function hostMatches(host, domain, filter) {
    if (filter == 'DOMAIN')
        return host === domain;
    if (filter == 'DOMAIN-SUFFIX')
        return host === domain || host.endsWith('.' + domain);
    if (filter == 'DOMAIN-KEYWORD')
        return host.indexOf(domain) !== -1;
    return false;
}

